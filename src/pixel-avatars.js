/* Baut ein SVG als Daten-URL. Waagerechte Läufe werden zusammengefasst,
   damit die Grafik klein bleibt. */
const PIXEL_CACHE = {};

function pixelAvatarUrl(key) {
  if (PIXEL_CACHE[key]) return PIXEL_CACHE[key];
  const a = PIXEL_ANIMALS[key];
  if (!a) return '';
  const rects = [];
  a.rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.') { x++; continue; }
      let w = 1;
      while (x + w < row.length && row[x + w] === ch) w++;
      const fill = a.colors[ch];
      if (fill) rects.push(`<rect x="${x}" y="${y}" width="${w}" height="1" fill="${fill}"/>`);
      x += w;
    }
  });
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 12 12" shape-rendering="crispEdges">'
    + `<rect width="12" height="12" fill="${a.bg}"/>${rects.join('')}</svg>`;
  PIXEL_CACHE[key] = 'data:image/svg+xml,' + encodeURIComponent(svg);
  return PIXEL_CACHE[key];
}
